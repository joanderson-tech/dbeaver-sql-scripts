CREATE TABLE IF NOT EXISTS USUARIO_PERMISSOES (
    USUARIO_ID INT8 NOT NULL,
    PERMISSAO_ID INT8 NOT NULL,
    CONSTRAINT USUARIO_PERMISSOES_PERMISSAO_ID_FK FOREIGN KEY (PERMISSAO_ID) REFERENCES PERMISSAO(PERMISSAO_ID),
    CONSTRAINT USUARIO_PERMISSOES_USUARIO_ID_FK FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO(USUARIO_ID)
);