SELECT * 
FROM comum.pessoa p 
WHERE p.nome ILIKE '%MARIA DOS NAVEGANTES SANTOS%';

select p.nome,
        u.login 
    from comum.usuario u 
    join comum.pessoa p on p.id_pessoa = u.id_pessoa 
    join rh.servidor s on s.id_pessoa = p.id_pessoa 
    join ensino.docente_turma dt on dt.id_docente = s.id_servidor 
    join ensino.turma t on t.id_turma = dt.id_turma 
    where dt.ativo and p.nome = 'MARIA DOS NAVEGANTES SANTOS DA FONSECA';