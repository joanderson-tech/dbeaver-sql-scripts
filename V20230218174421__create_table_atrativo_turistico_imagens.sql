CREATE TABLE IF NOT EXISTS ATRATIVO_TURISTICO_IMAGENS (
    ATRATIVO_TURISTICO_ID INT8 NOT NULL,
    CLOUD_OBJECT VARCHAR(255) NOT NULL,
    DESCRICAO_ARQUIVO VARCHAR(255) NOT NULL,
    DATA_DE_UPLOAD TIMESTAMP(6) NOT NULL,
    CONSTRAINT ATRATIVO_TURISTICO_IMAGENS_ATRATIVO_TURISTICO_ID_FK FOREIGN KEY (ATRATIVO_TURISTICO_ID) REFERENCES ATRATIVO_TURISTICO(ATRATIVO_TURISTICO_ID)
);
