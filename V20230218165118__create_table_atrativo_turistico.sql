CREATE SEQUENCE IF NOT EXISTS ATRATIVO_TURISTICO_SEQUENCE
    INCREMENT BY 1
    START WITH 1
    MAXVALUE 9223372036854775807
    MINVALUE 1
    NO CYCLE;

CREATE TABLE IF NOT EXISTS ATRATIVO_TURISTICO (
    ATRATIVO_TURISTICO_ID INT8 NOT NULL DEFAULT nextval('ATRATIVO_TURISTICO_SEQUENCE'),
    DATA_DE_CRIACAO TIMESTAMP(6) NULL,
    DESCRICAO VARCHAR(1000) NULL,
    CEP VARCHAR(255) NULL,
    COMPLEMENTOS VARCHAR(255) NULL,
    LATITUDE VARCHAR(255) NULL,
    LOGRADOURO VARCHAR(255) NULL,
    NUMERO VARCHAR(255) NULL,
    COMPLEMENTO VARCHAR(255) NULL,
    BAIRRO VARCHAR(255) NULL,
    LONGITUDE VARCHAR(255) NULL,
    PONTO_DE_REFERENCIA VARCHAR(255) NULL,
    MUNICIPIO_ID INT8 NULL,
    NOME VARCHAR(255) NOT NULL,
    LEGENDA VARCHAR(255) NULL,
    LINK VARCHAR(255) NULL,
    ULTIMA_ATUALIZACAO TIMESTAMP(6) NULL,
    VALIDADO BOOL NOT NULL DEFAULT FALSE,
    CRIADO_POR_USUARIO_ID INT8 NULL,
    TIPO_ATRATIVO_TURISTICO_ID INT8 NULL,
    USUARIO_QUE_VALIDOU_ID INT8 NULL,

    CONSTRAINT ATRATIVO_TURISTICO_PKEY PRIMARY KEY (ATRATIVO_TURISTICO_ID),
    CONSTRAINT ATRATIVO_TURISTICO_CRIADO_POR_USUARIO_ID_FK FOREIGN KEY (CRIADO_POR_USUARIO_ID) REFERENCES USUARIO(USUARIO_ID) ON DELETE SET DEFAULT,
    CONSTRAINT ATRATIVO_TURISTICO_USUARIO_QUE_VALIDOU_ID_FK FOREIGN KEY (USUARIO_QUE_VALIDOU_ID) REFERENCES USUARIO(USUARIO_ID) ON DELETE SET DEFAULT,
    CONSTRAINT ATRATIVO_TURISTICO_TIPO_ATRATIVO_TURISTICO_ID_FK FOREIGN KEY (TIPO_ATRATIVO_TURISTICO_ID) REFERENCES TIPO_ATRATIVO_TURISTICO(TIPO_ATRATIVO_TURISTICO_ID) ON DELETE SET DEFAULT,
    CONSTRAINT ATRATIVO_TURISTICO_MUNICIPIO_ID_FK FOREIGN KEY (MUNICIPIO_ID) REFERENCES MUNICIPIO(MUNICIPIO_ID) ON DELETE SET DEFAULT
);

