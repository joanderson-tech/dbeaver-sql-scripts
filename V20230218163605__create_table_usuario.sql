CREATE SEQUENCE IF NOT EXISTS USUARIO_SEQUENCE
    INCREMENT BY 1
    START WITH 1
    MAXVALUE 9223372036854775807
    MINVALUE 1
    NO CYCLE;

CREATE TABLE IF NOT EXISTS USUARIO (
    USUARIO_ID INT8 NOT NULL DEFAULT nextval('USUARIO_SEQUENCE'),
    PRIMEIRO_NOME VARCHAR(255) NOT NULL,
    ULTIMO_NOME VARCHAR(255) NOT NULL,
    EMAIL VARCHAR(255) NOT NULL,
    SENHA_ENCRIPITADA VARCHAR(255) NOT NULL,
    DATA_DE_CRIACAO TIMESTAMP(6) NOT NULL,
    ULTIMA_ATUALIZACAO TIMESTAMP(6) NULL,
    CONSTRAINT USUARIO_PKEY PRIMARY KEY (USUARIO_ID),
    CONSTRAINT USUARIO_EMAIL_UNIQUE UNIQUE (EMAIL)
);