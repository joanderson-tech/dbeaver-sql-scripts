CREATE SEQUENCE IF NOT EXISTS MUNICIPIO_SEQUENCE
    INCREMENT BY 1
    START WITH 1
    MAXVALUE 9223372036854775807
    MINVALUE 1
    NO CYCLE;

CREATE TABLE MUNICIPIO (
    MUNICIPIO_ID INT8 NOT NULL DEFAULT nextval('MUNICIPIO_SEQUENCE'),
    DATA_DE_CRIACAO TIMESTAMP(6) NOT NULL,
    NOME VARCHAR(255) NOT NULL,
    UF_SIGLA VARCHAR(255) NOT NULL,
    ULTIMA_ATUALIZACAO TIMESTAMP(6) NULL,
    CONSTRAINT MUNICIPIO_PKEY PRIMARY KEY (MUNICIPIO_ID)
);