CREATE TABLE IF NOT EXISTS ATRATIVO_TURISTICO_INFORMACOES_ADICIONAIS (
    ATRATIVO_TURISTICO_ID INT8 NOT NULL,
    AUTOR_IMAGEM VARCHAR(255) NULL,
    INFO_DESCRICAO VARCHAR(255) NULL,
    CLOUD_OBJECT VARCHAR(255) NULL,
    DESCRICAO_ARQUIVO VARCHAR(255) NULL,
    DATA_DE_UPLOAD TIMESTAMP(6) NULL,
    LEGENDA_IMAGEM VARCHAR(255) NULL,
    NOME VARCHAR(255) NOT NULL,

    CONSTRAINT ATRATIVO_TURISTICO_INFORMACOES_ADICIONAIS_ATRATIVO_TURISTICO_ID_FK FOREIGN KEY (ATRATIVO_TURISTICO_ID) REFERENCES ATRATIVO_TURISTICO(ATRATIVO_TURISTICO_ID)
);
